func WriteContainerRenameOverlay(dataDir, prefix string) (string, error) {
	if prefix == "" {
		return "", fmt.Errorf("container prefix must be non-empty")
	}
	if err := os.MkdirAll(dataDir, 0o700); err != nil {
		return "", fmt.Errorf("create data dir %s: %w", dataDir, err)
	}

	var b strings.Builder
	b.WriteString("# Generated by canton-devkit. Two functions:\n")
	b.WriteString("#   1. Renames every hardcoded container_name so multiple\n")
	b.WriteString("#      instances can coexist on a single Docker daemon.\n")
	b.WriteString("#   2. Relaxes nginx's depends_on:splice from\n")
	b.WriteString("#      service_healthy to service_started — splice's\n")
	b.WriteString("#      onboarding outlasts compose's dep-health budget.\n")
	b.WriteString("#      Real readiness is polled by WaitForHealthy.\n")
	b.WriteString("services:\n")

	names := append([]string(nil), splice610Containers...)
	sort.Strings(names)
	for _, svc := range names {
		fmt.Fprintf(&b, "  %s:\n    container_name: %s%s\n", svc, prefix, svc)
		if svc == "nginx" {
			// Per-key merge: compose merges depends_on by service name,
			// so this override applies ONLY to the splice entry — the
			// other nginx dependencies (wallet-web-ui-*) keep their
			// upstream-declared conditions.
			b.WriteString("    depends_on:\n")
			b.WriteString("      splice:\n")
			b.WriteString("        condition: service_started\n")
		}
	}

	path := filepath.Join(dataDir, "containers.yaml")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return "", fmt.Errorf("write overlay %s: %w", path, err)
	}
	return path, nil
}

