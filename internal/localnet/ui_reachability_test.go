func TestUIReachabilityCheck_UnreachableWarnsWithRemediation(t *testing.T) {
	t.Setenv("CANTON_DEVKIT_REGISTRY", t.TempDir())
	s := seedReachabilityInstance(t, "old-instance", registry.StatusRunning,
		map[string]int{"app_user_ui": 4485, "sv_ui": 4487})
	staleYAML := "services:\n  nginx:\n    ports: !override\n      - \"127.0.0.1:32771:2000\"\n"
	if err := os.WriteFile(filepath.Join(s.DataDir, "loopback-ports.yaml"), []byte(staleYAML), 0o644); err != nil {
		t.Fatalf("write overlay: %v", err)
	}
	probe := &recordingUIProbe{failWith: map[string]error{
		"http://localhost:4485": io.EOF,
		"http://localhost:4487": io.EOF,
	}}
	installFakeUIProbe(t, probe.probe)

	got := uiReachabilityCheck(context.Background())
	if got.Status != docker.StatusWarn {
		t.Fatalf("status = %v, want warn; detail=%q", got.Status, got.Detail)
	}
	for _, want := range []string{"old-instance/app_user_ui", "empty reply", "stale loopback-ports.yaml"} {
		if !strings.Contains(got.Detail, want) {
			t.Errorf("detail missing %q\ndetail: %s", want, got.Detail)
		}
	}
	for _, want := range []string{"dpm localnet up --name old-instance", "Recreate in the Web UI"} {
		if !strings.Contains(got.Remediation, want) {
			t.Errorf("remediation missing %q\nremediation: %s", want, got.Remediation)
		}
	}
}

