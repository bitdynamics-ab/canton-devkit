// TestCollectDoctor_IncludesUIReachability pins the doctor wiring: the
// probe result lands in the Network section (label contains "ports")
// and a broken instance degrades it to warn without flipping rep.OK.
func TestCollectDoctor_IncludesUIReachability(t *testing.T) {
	t.Setenv("CANTON_DEVKIT_REGISTRY", t.TempDir())
	seedReachabilityInstance(t, "old-instance", registry.StatusRunning, map[string]int{"app_user_ui": 4485})
	probe := &recordingUIProbe{failWith: map[string]error{"http://localhost:4485": io.EOF}}
	installFakeUIProbe(t, probe.probe)

	rep, err := CollectDoctor(context.Background(), DoctorOptions{
		GOOS:       "linux",
		GOARCH:     "amd64",
		ListenFunc: fakeListenOK,
		Prober: func(context.Context, docker.Options) *docker.Report {
			return &docker.Report{Results: []docker.CheckResult{{Name: "Docker CLI", Status: docker.StatusOK}}}
		},
	})
	if err != nil {
		t.Fatalf("CollectDoctor: %v", err)
	}
	var section string
	var check types.PreflightCheck
	for _, sec := range rep.Sections {
		for _, c := range sec.Checks {
			if c.Label == uiReachabilityCheckName {
				section, check = sec.Title, c
			}
		}
	}
	if section != "Network" {
		t.Errorf("check filed under %q, want Network", section)
	}
	if check.Result != "warn" {
		t.Errorf("result = %q, want warn", check.Result)
	}
	if len(check.Remediation) == 0 || !strings.Contains(strings.Join(check.Remediation, "\n"), "old-instance") {
		t.Errorf("remediation should name the instance, got %v", check.Remediation)
	}
	if !rep.OK {
		t.Error("rep.OK = false; UI reachability is advisory and must not fail doctor")
	}
}

