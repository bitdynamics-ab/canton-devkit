func TestHasStaleLoopbackOverlay(t *testing.T) {
	stale := `# Generated by canton-devkit.
services:
  nginx:
    ports: !override
      - "127.0.0.1:32771:2000"
      - "127.0.0.1:32772:3000"
      - "127.0.0.1:32773:4000"
`
	current := `# Generated by canton-devkit.
services:
  nginx:
    ports: !override
      - "127.0.0.1:${APP_USER_UI_PORT}:${APP_USER_UI_PORT}"
      - "127.0.0.1:${SV_UI_PORT}:${SV_UI_PORT}"
  postgres:
    ports: !override
      - "127.0.0.1:${DB_PORT}:5432"
`
	cases := []struct {
		name    string
		content string // "" = don't write the file
		want    bool
	}{
		{"pre-136 fixed container ports", stale, true},
		{"current env-templated ports", current, false},
		{"missing overlay", "", false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := t.TempDir()
			if c.content != "" {
				if err := os.WriteFile(filepath.Join(dir, "loopback-ports.yaml"), []byte(c.content), 0o644); err != nil {
					t.Fatalf("write overlay: %v", err)
				}
			}
			if got := hasStaleLoopbackOverlay(dir); got != c.want {
				t.Errorf("hasStaleLoopbackOverlay = %v, want %v", got, c.want)
			}
		})
	}
	if hasStaleLoopbackOverlay("") {
		t.Error("empty dataDir must not count as stale")
	}
}

func TestProbeUIEndpoints_MarksOnlyBrowserUIPorts(t *testing.T) {
	probe := &recordingUIProbe{failWith: map[string]error{
		"http://localhost:4485": io.EOF,
	}}
	installFakeUIProbe(t, probe.probe)

	s := &registry.State{
		Name:    "demo",
		DataDir: t.TempDir(),
		Ports: map[string]int{
			"app_user_ui": 4485,
			"sv_ui":       4487,
			"swagger_ui":  9090, // http, but not overlay-affected: not probed
			"postgres":    5432,
		},
	}
	endpoints := endpointsFromPorts(s.Ports)
	probeUIEndpoints(context.Background(), s, endpoints)

	byPort := map[int]types.Endpoint{}
	for _, e := range endpoints {
		byPort[e.Port] = e
	}
	if got := byPort[4485]; got.Reachability != types.ReachabilityUnreachable ||
		!strings.Contains(got.ReachabilityDetail, "empty reply") {
		t.Errorf("app_user_ui = %+v, want unreachable with empty-reply detail", got)
	}
	if got := byPort[4487]; got.Reachability != types.ReachabilityOK {
		t.Errorf("sv_ui reachability = %q, want %q", got.Reachability, types.ReachabilityOK)
	}
	for _, port := range []int{9090, 5432} {
		if got := byPort[port]; got.Reachability != "" {
			t.Errorf("port %d reachability = %q, want unprobed", port, got.Reachability)
		}
	}
	if calls := probe.called(); len(calls) != 2 {
		t.Errorf("probe called for %v, want exactly the two UI ports", calls)
	}
}

